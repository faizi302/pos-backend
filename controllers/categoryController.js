// ======================================================
// UPDATE CATEGORY
// ======================================================

export const updateCategory = async (
  req,
  res,
  next
) => {
  try {
    const { id } =
      req.params;

    // ==================================================
    // VALIDATE ID
    // ==================================================

    if (
      !isValidObjectId(id)
    ) {
      return errorResponse(
        res,
        400,
        "Invalid category ID"
      );
    }

    const {
      name,
      businessType,
      description,
      isActive,
      removeImage,
    } = req.body;

    // ==================================================
    // FIND CATEGORY WITH TENANT ISOLATION
    // ==================================================

    const result =
      await buildTenantQuery(
        req,
        {
          _id: id,
        }
      );

    if (result.error) {
      return errorResponse(
        res,
        400,
        result.error
      );
    }

    const category =
      await Category.findOne(
        result.query
      );

    if (!category) {
      return errorResponse(
        res,
        404,
        "Category not found"
      );
    }

    const businessId =
      category.business?.toString();

    // ==================================================
    // BUSINESS TYPE
    // ==================================================

    let newBusinessType =
      category.businessType
        ? category.businessType.toString()
        : null;

    // ==================================================
    // SUPER ADMIN
    // ==================================================

    if (isSuperAdmin(req.user)) {
      if (
        businessType !==
        undefined
      ) {
        // Allow Super Admin to remove
        // Business Type.

        if (
          businessType === null ||
          businessType === ""
        ) {
          newBusinessType =
            null;
        } else {
          if (
            !isValidObjectId(
              businessType
            )
          ) {
            return errorResponse(
              res,
              400,
              "Invalid business type ID"
            );
          }

          const validBusinessType =
            await validateBusinessType(
              businessType,
              businessId
            );

          if (
            !validBusinessType
          ) {
            return errorResponse(
              res,
              400,
              "Business type does not belong to this business"
            );
          }

          newBusinessType =
            businessType.toString();
        }
      }
    }

    // ==================================================
    // ADMIN / MANAGER
    // ==================================================

    else {
      const tenant =
        await requireTenantContext(
          req.user
        );

      if (tenant.error) {
        return errorResponse(
          res,
          400,
          tenant.error
        );
      }

      // NEVER trust businessType
      // from request.

      newBusinessType =
        tenant.context.businessType.toString();
    }

    // ==================================================
    // UPDATE NAME
    // ==================================================

    if (
      name !== undefined
    ) {
      if (
        !name?.trim()
      ) {
        return errorResponse(
          res,
          400,
          "Category name cannot be empty"
        );
      }

      category.name =
        formatCategoryName(
          name
        );

      // ================================================
      // ALWAYS REGENERATE SLUG
      // ================================================

      category.slug =
        generateSlug(
          category.name
        );
    }

    // ==================================================
    // UPDATE BUSINESS TYPE
    // ==================================================

    category.businessType =
      newBusinessType || null;

    // ==================================================
    // UPDATE DESCRIPTION
    // ==================================================

    if (
      description !==
      undefined
    ) {
      category.description =
        description?.trim() ||
        "";
    }

    // ==================================================
    // UPDATE ACTIVE STATUS
    // ==================================================

    if (
      isActive !== undefined
    ) {
      category.isActive =
        parseBoolean(
          isActive,
          category.isActive
        );
    }

    // ==================================================
    // REMOVE IMAGE
    // ==================================================

    if (
      parseBoolean(
        removeImage,
        false
      ) &&
      category.image?.publicId
    ) {
      await deleteFromCloudinary(
        category.image.publicId
      );

      category.image = {
        url: null,
        publicId: null,
        assetId: null,
      };
    }

    // ==================================================
    // UPLOAD NEW IMAGE
    // ==================================================

    if (req.file) {
      // Delete old image first

      if (
        category.image?.publicId
      ) {
        await deleteFromCloudinary(
          category.image.publicId
        );
      }

      const uploadedImage =
        await uploadToCloudinary(
          req.file.buffer,
          "pos/categories"
        );

      category.image = {
        url:
          uploadedImage.secure_url,

        publicId:
          uploadedImage.public_id,

        assetId:
          uploadedImage.asset_id ||
          null,
      };
    }

    // ==================================================
    // DUPLICATE CATEGORY CHECK
    // ==================================================

    const duplicate =
      await Category.findOne({
        _id: {
          $ne:
            category._id,
        },

        business:
          businessId,

        businessType:
          newBusinessType ||
          null,

        name:
          category.name,
      });

    if (duplicate) {
      return errorResponse(
        res,
        409,
        "Category with this name already exists"
      );
    }

    // ==================================================
    // UPDATE AUDIT
    // ==================================================

    category.updatedBy =
      req.user._id;

    // ==================================================
    // SAVE
    // ==================================================

    await category.save();

    // ==================================================
    // POPULATE RESPONSE
    // ==================================================

    const updatedCategory =
      await Category.findById(
        category._id
      )
        .populate(
          "business",
          "name"
        )
        .populate(
          "businessType",
          "name"
        )
        .populate(
          "createdBy",
          "name email"
        )
        .populate(
          "updatedBy",
          "name email"
        );

    // ==================================================
    // RESPONSE
    // ==================================================

    return successResponse(
      res,
      200,
      "Category updated successfully",
      updatedCategory
    );
  } catch (error) {
    // MongoDB duplicate key

    if (
      error?.code ===
      11000
    ) {
      return errorResponse(
        res,
        409,
        "Category with this name already exists"
      );
    }

    next(error);
  }
};

// ======================================================
// DELETE CATEGORY
// ======================================================
//
// Soft delete.
// Image is NOT deleted because category can be restored.
//

export const deleteCategory = async (
  req,
  res,
  next
) => {
  try {
    const { id } =
      req.params;

    // ==================================================
    // VALIDATE ID
    // ==================================================

    if (
      !isValidObjectId(id)
    ) {
      return errorResponse(
        res,
        400,
        "Invalid category ID"
      );
    }

    // ==================================================
    // TENANT QUERY
    // ==================================================

    const result =
      await buildTenantQuery(
        req,
        {
          _id: id,
        }
      );

    if (result.error) {
      return errorResponse(
        res,
        400,
        result.error
      );
    }

    // ==================================================
    // FIND CATEGORY
    // ==================================================

    const category =
      await Category.findOne(
        result.query
      );

    if (!category) {
      return errorResponse(
        res,
        404,
        "Category not found"
      );
    }

    // ==================================================
    // ALREADY DELETED
    // ==================================================

    if (
      !category.isActive
    ) {
      return errorResponse(
        res,
        400,
        "Category is already inactive"
      );
    }

    // ==================================================
    // SOFT DELETE
    // ==================================================

    category.isActive =
      false;

    category.updatedBy =
      req.user._id;

    await category.save();

    // ==================================================
    // RESPONSE
    // ==================================================

    return successResponse(
      res,
      200,
      "Category deleted successfully"
    );
  } catch (error) {
    next(error);
  }
};

// ======================================================
// RESTORE CATEGORY
// ======================================================

export const restoreCategory = async (
  req,
  res,
  next
) => {
  try {
    const { id } =
      req.params;

    // ==================================================
    // VALIDATE ID
    // ==================================================

    if (
      !isValidObjectId(id)
    ) {
      return errorResponse(
        res,
        400,
        "Invalid category ID"
      );
    }

    // ==================================================
    // TENANT QUERY
    // ==================================================

    const result =
      await buildTenantQuery(
        req,
        {
          _id: id,
        }
      );

    if (result.error) {
      return errorResponse(
        res,
        400,
        result.error
      );
    }

    // ==================================================
    // FIND CATEGORY
    // ==================================================

    const category =
      await Category.findOne(
        result.query
      );

    if (!category) {
      return errorResponse(
        res,
        404,
        "Category not found"
      );
    }

    // ==================================================
    // ALREADY ACTIVE
    // ==================================================

    if (
      category.isActive
    ) {
      return errorResponse(
        res,
        400,
        "Category is already active"
      );
    }

    // ==================================================
    // CHECK DUPLICATE ACTIVE CATEGORY
    // ==================================================
    //
    // Important because this category may have been
    // soft-deleted while another active category with
    // the same business/businessType/name exists.
    //

    const duplicate =
      await Category.findOne({
        _id: {
          $ne:
            category._id,
        },

        business:
          category.business,

        businessType:
          category.businessType,

        name:
          category.name,

        isActive: true,
      });

    if (duplicate) {
      return errorResponse(
        res,
        409,
        "An active category with this name already exists"
      );
    }

    // ==================================================
    // RESTORE
    // ==================================================

    category.isActive =
      true;

    category.updatedBy =
      req.user._id;

    await category.save();

    // ==================================================
    // POPULATE
    // ==================================================

    const restoredCategory =
      await Category.findById(
        category._id
      )
        .populate(
          "business",
          "name"
        )
        .populate(
          "businessType",
          "name"
        )
        .populate(
          "createdBy",
          "name email"
        )
        .populate(
          "updatedBy",
          "name email"
        );

    // ==================================================
    // RESPONSE
    // ==================================================

    return successResponse(
      res,
      200,
      "Category restored successfully",
      restoredCategory
    );
  } catch (error) {
    // MongoDB duplicate key

    if (
      error?.code ===
      11000
    ) {
      return errorResponse(
        res,
        409,
        "Category with this name already exists"
      );
    }

    next(error);
  }
};