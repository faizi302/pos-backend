// ======================================================
// HELPERS
// ======================================================

const getUserRole = (user) =>
  user?.role?.slug ||
  user?.role?.name?.toLowerCase();

const isSuperAdmin = (user) =>
  getUserRole(user) === "super-admin";

const isValidObjectId = (id) =>
  mongoose.Types.ObjectId.isValid(id);

// ======================================================
// FORMAT CATEGORY NAME
// ======================================================
//
// Examples:
//
// "ipads"
//      -> "Ipads"
//
// "mobile phones"
//      -> "Mobile Phones"
//
// "deLL zONE"
//      -> "DeLL ZONE"
//
// "  mobile   phones  "
//      -> "Mobile Phones"
//
// We only capitalize the first character of each word.
// Existing characters remain unchanged.
//

const formatCategoryName = (value = "") => {
  return value
    .trim()
    .replace(/\s+/g, " ")
    .replace(/\b\w/g, (char) =>
      char.toUpperCase()
    );
};

// ======================================================
// GENERATE SLUG
// ======================================================
//
// Examples:
//
// "Mobiles"
//      -> "mobiles"
//
// "Mobile Phones"
//      -> "mobile-phones"
//
// "DeLL ZONE"
//      -> "dell-zone"
//
// Slug is always generated by backend.
// Frontend slug is NOT trusted.
//

const generateSlug = (value = "") => {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-");
};

// ======================================================
// PARSE BOOLEAN
// ======================================================

const parseBoolean = (
  value,
  defaultValue = undefined
) => {
  if (
    value === undefined ||
    value === null ||
    value === ""
  ) {
    return defaultValue;
  }

  if (
    value === true ||
    value === "true" ||
    value === 1 ||
    value === "1"
  ) {
    return true;
  }

  if (
    value === false ||
    value === "false" ||
    value === 0 ||
    value === "0"
  ) {
    return false;
  }

  return defaultValue;
};

// ======================================================
// GET EFFECTIVE BUSINESS CONTEXT
// ======================================================
//
// Super Admin:
//   Usually has no business assigned.
//
// Admin:
//   Gets business + businessType directly from user.
//
// Manager:
//   Inherits business + businessType from Admin
//   through createdBy.
//
// ======================================================

const getEffectiveBusinessContext = async (user) => {
  if (!user) {
    return null;
  }

  // ====================================================
  // ADMIN
  // ====================================================

  if (user.business) {
    return {
      business:
        user.business?._id ||
        user.business,

      businessType:
        user.businessType?._id ||
        user.businessType ||
        null,
    };
  }

  // ====================================================
  // MANAGER
  // ====================================================

  if (user.createdBy) {
    const creator =
      await User.findById(user.createdBy)
        .select("business businessType")
        .lean();

    if (!creator) {
      return null;
    }

    return {
      business:
        creator.business?._id ||
        creator.business ||
        null,

      businessType:
        creator.businessType?._id ||
        creator.businessType ||
        null,
    };
  }

  return null;
};

// ======================================================
// REQUIRE TENANT CONTEXT
// ======================================================
//
// Admin and Manager must have:
//
// Business
// +
// Business Type
//
// This prevents an Admin assigned only to a Business
// from seeing categories belonging to multiple
// Business Types.
//

const requireTenantContext = async (user) => {
  const context =
    await getEffectiveBusinessContext(user);

  if (!context?.business) {
    return {
      error:
        "Business context not found for this user",
    };
  }

  if (!context?.businessType) {
    return {
      error:
        "Business type context not found for this user",
    };
  }

  return {
    context,
  };
};

// ======================================================
// VALIDATE BUSINESS
// ======================================================

const validateBusiness = async (businessId) => {
  if (
    !businessId ||
    !isValidObjectId(businessId)
  ) {
    return null;
  }

  return Business.findOne({
    _id: businessId,
    isActive: true,
  }).lean();
};

// ======================================================
// VALIDATE BUSINESS TYPE
// ======================================================
//
// Business Type MUST belong to the selected Business.
//

const validateBusinessType = async (
  businessTypeId,
  businessId
) => {
  if (
    !businessTypeId ||
    !isValidObjectId(businessTypeId) ||
    !businessId ||
    !isValidObjectId(businessId)
  ) {
    return null;
  }

  return BusinessType.findOne({
    _id: businessTypeId,
    business: businessId,
    isActive: true,
  }).lean();
};

// ======================================================
// BUILD TENANT QUERY
// ======================================================
//
// Super Admin:
//   Optional business/businessType filters.
//
// Admin / Manager:
//   ALWAYS forced to their assigned context.
//

const buildTenantQuery = async (
  req,
  extraQuery = {}
) => {
  const query = {
    ...extraQuery,
  };

  // ====================================================
  // SUPER ADMIN
  // ====================================================

  if (isSuperAdmin(req.user)) {
    if (req.query.business) {
      if (
        !isValidObjectId(
          req.query.business
        )
      ) {
        return {
          error: "Invalid business ID",
        };
      }

      query.business =
        req.query.business;
    }

    if (req.query.businessType) {
      if (
        !isValidObjectId(
          req.query.businessType
        )
      ) {
        return {
          error:
            "Invalid business type ID",
        };
      }

      query.businessType =
        req.query.businessType;
    }

    return {
      query,
    };
  }

  // ====================================================
  // ADMIN / MANAGER
  // ====================================================

  const tenant =
    await requireTenantContext(req.user);

  if (tenant.error) {
    return {
      error: tenant.error,
    };
  }

  query.business =
    tenant.context.business;

  query.businessType =
    tenant.context.businessType;

  return {
    query,
  };
};

// ======================================================
// CREATE CATEGORY
// ======================================================

export const createCategory = async (
  req,
  res,
  next
) => {
  try {
    const {
      name,
      businessType,
      description,
      isActive,
    } = req.body;

    // ==================================================
    // BASIC VALIDATION
    // ==================================================

    if (!name?.trim()) {
      return errorResponse(
        res,
        400,
        "Category name is required"
      );
    }

    // ==================================================
    // FORMAT NAME
    // ==================================================

    const formattedName =
      formatCategoryName(name);

    if (!formattedName) {
      return errorResponse(
        res,
        400,
        "Category name is required"
      );
    }

    // ==================================================
    // GENERATE SLUG
    // ==================================================

    const generatedSlug =
      generateSlug(formattedName);

    if (!generatedSlug) {
      return errorResponse(
        res,
        400,
        "Unable to generate category slug"
      );
    }

    // ==================================================
    // GET BUSINESS CONTEXT
    // ==================================================

    let businessId = null;
    let businessTypeId = null;

    // ==================================================
    // SUPER ADMIN
    // ==================================================

    if (isSuperAdmin(req.user)) {
      businessId =
        req.body.business ||
        req.query.business ||
        null;

      businessTypeId =
        businessType || null;
    }

    // ==================================================
    // ADMIN / MANAGER
    // ==================================================

    else {
      const tenant =
        await requireTenantContext(
          req.user
        );

      if (tenant.error) {
        return errorResponse(
          res,
          400,
          tenant.error
        );
      }

      businessId =
        tenant.context.business;

      businessTypeId =
        tenant.context.businessType;
    }

    // ==================================================
    // BUSINESS REQUIRED
    // ==================================================

    if (!businessId) {
      return errorResponse(
        res,
        400,
        "Business is required"
      );
    }

    if (
      !isValidObjectId(businessId)
    ) {
      return errorResponse(
        res,
        400,
        "Invalid business ID"
      );
    }

    // ==================================================
    // VALIDATE BUSINESS
    // ==================================================

    const business =
      await validateBusiness(
        businessId
      );

    if (!business) {
      return errorResponse(
        res,
        404,
        "Business not found or inactive"
      );
    }

    // ==================================================
    // BUSINESS TYPE REQUIRED FOR ADMIN/MANAGER
    // ==================================================

    if (
      !isSuperAdmin(req.user) &&
      !businessTypeId
    ) {
      return errorResponse(
        res,
        400,
        "Business type is required for this user"
      );
    }

    // ==================================================
    // VALIDATE BUSINESS TYPE
    // ==================================================

    if (businessTypeId) {
      const validBusinessType =
        await validateBusinessType(
          businessTypeId,
          businessId
        );

      if (!validBusinessType) {
        return errorResponse(
          res,
          400,
          "Business type does not belong to this business"
        );
      }
    }

    // ==================================================
    // DUPLICATE CATEGORY CHECK
    // ==================================================

    const existingCategory =
      await Category.findOne({
        business: businessId,

        businessType:
          businessTypeId || null,

        name: formattedName,
      });

    if (existingCategory) {
      return errorResponse(
        res,
        409,
        "Category with this name already exists"
      );
    }

    // ==================================================
    // UPLOAD IMAGE
    // ==================================================

    let image = {
      url: null,
      publicId: null,
      assetId: null,
    };

    if (req.file) {
      const uploadedImage =
        await uploadToCloudinary(
          req.file.buffer,
          "pos/categories"
        );

      image = {
        url:
          uploadedImage.secure_url,

        publicId:
          uploadedImage.public_id,

        assetId:
          uploadedImage.asset_id ||
          null,
      };
    }

    // ==================================================
    // CREATE CATEGORY
    // ==================================================

    const category =
      await Category.create({
        business: businessId,

        businessType:
          businessTypeId || null,

        name: formattedName,

        slug: generatedSlug,

        image,

        description:
          description?.trim() || "",

        isActive:
          parseBoolean(
            isActive,
            true
          ),

        createdBy:
          req.user._id,
      });

    // ==================================================
    // POPULATE RESPONSE
    // ==================================================

    const populatedCategory =
      await Category.findById(
        category._id
      )
        .populate(
          "business",
          "name"
        )
        .populate(
          "businessType",
          "name"
        )
        .populate(
          "createdBy",
          "name email"
        );

    return successResponse(
      res,
      201,
      "Category created successfully",
      populatedCategory
    );
  } catch (error) {
    // MongoDB duplicate key
    if (error?.code === 11000) {
      return errorResponse(
        res,
        409,
        "Category with this name already exists"
      );
    }

    next(error);
  }
};

// ======================================================
// GET ALL CATEGORIES
// ======================================================

export const getAllCategories = async (
  req,
  res,
  next
) => {
  try {
    const {
      search,
      businessType,
      isActive,
      page = 1,
      limit = 20,
    } = req.query;

    let query = {};

    // ==================================================
    // TENANT ISOLATION
    // ==================================================

    if (isSuperAdmin(req.user)) {
      // -----------------------------------------------
      // SUPER ADMIN
      // -----------------------------------------------

      if (req.query.business) {
        if (
          !isValidObjectId(
            req.query.business
          )
        ) {
          return errorResponse(
            res,
            400,
            "Invalid business ID"
          );
        }

        query.business =
          req.query.business;
      }

      if (businessType) {
        if (
          !isValidObjectId(
            businessType
          )
        ) {
          return errorResponse(
            res,
            400,
            "Invalid business type ID"
          );
        }

        query.businessType =
          businessType;
      }
    } else {
      // -----------------------------------------------
      // ADMIN / MANAGER
      // -----------------------------------------------

      const tenant =
        await requireTenantContext(
          req.user
        );

      if (tenant.error) {
        return errorResponse(
          res,
          400,
          tenant.error
        );
      }

      query.business =
        tenant.context.business;

      query.businessType =
        tenant.context.businessType;
    }

    // ==================================================
    // SEARCH
    // ==================================================

    if (search?.trim()) {
      query.$or = [
        {
          name: {
            $regex:
              search.trim(),
            $options: "i",
          },
        },
        {
          slug: {
            $regex:
              search.trim(),
            $options: "i",
          },
        },
      ];
    }

    // ==================================================
    // ACTIVE FILTER
    // ==================================================

    if (isActive !== undefined) {
      const parsedActive =
        parseBoolean(isActive);

      if (
        parsedActive !== undefined
      ) {
        query.isActive =
          parsedActive;
      }
    }

    // ==================================================
    // PAGINATION
    // ==================================================

    const pageNumber =
      Math.max(
        Number(page) || 1,
        1
      );

    const limitNumber =
      Math.min(
        Math.max(
          Number(limit) || 20,
          1
        ),
        100
      );

    const skip =
      (pageNumber - 1) *
      limitNumber;

    // ==================================================
    // FETCH
    // ==================================================

    const [
      categories,
      total,
    ] = await Promise.all([
      Category.find(query)
        .populate(
          "business",
          "name"
        )
        .populate(
          "businessType",
          "name"
        )
        .populate(
          "createdBy",
          "name email"
        )
        .populate(
          "updatedBy",
          "name email"
        )
        .sort({
          createdAt: -1,
        })
        .skip(skip)
        .limit(limitNumber)
        .lean(),

      Category.countDocuments(
        query
      ),
    ]);

    // ==================================================
    // RESPONSE
    // ==================================================

    return successResponse(
      res,
      200,
      "Categories fetched successfully",
      {
        categories,

        pagination: {
          page: pageNumber,

          limit: limitNumber,

          total,

          totalPages:
            Math.ceil(
              total /
                limitNumber
            ),
        },
      }
    );
  } catch (error) {
    next(error);
  }
};

